// ===== CONTRIBUTION HEATMAP DATA =====
export function generateContributionData(): { date: string; count: number }[] {
  const data: { date: string; count: number }[] = [];
  const today = new Date();
  for (let i = 365; i >= 0; i--) {
    const date = new Date(today);
    date.setDate(date.getDate() - i);
    const dateStr = date.toISOString().split('T')[0];
    // Generate realistic-looking contribution data
    const dayOfWeek = date.getDay();
    const isWeekend = dayOfWeek === 0 || dayOfWeek === 6;
    const baseChance = isWeekend ? 0.3 : 0.7;
    const hasContribution = Math.random() < baseChance;
    const count = hasContribution ? Math.floor(Math.random() * 8) + 1 : 0;
    data.push({ date: dateStr, count });
  }
  return data;
}

